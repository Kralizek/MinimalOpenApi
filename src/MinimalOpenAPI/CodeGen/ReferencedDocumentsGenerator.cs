using System.Text;

using Microsoft.CodeAnalysis;

namespace MinimalOpenAPI.Generator.CodeGen;

/// <summary>
/// Registers the OpenAPI documents declared in referenced assemblies (for example contract class
/// libraries) from the consuming project.
/// <para>
/// Every generated document marks its assembly with <c>[assembly: MinimalOpenApiDocument(typeof(...))]</c>.
/// This generator reads those attributes from the compilation's metadata references and emits one
/// module initializer that calls each referenced entry point's <c>Register()</c> directly. A library's
/// own module initializer only runs once one of its members is accessed, which may happen after
/// <c>AddMinimalOpenApi()</c>; the consuming project's initializer always runs when that project's
/// code first runs (for an application, before <c>Main</c>), and the direct calls load each library.
/// Discovery happens at compile time, so no runtime assembly scanning is involved.
/// </para>
/// </summary>
internal static class ReferencedDocumentsGenerator
{
    private const string RuntimeAssemblyName = "MinimalOpenAPI";
    private const string DocumentAttributeName = "MinimalOpenAPI.MinimalOpenApiDocumentAttribute";

    /// <summary>Hint name of the generated source.</summary>
    public const string HintName = "MinimalOpenApi/MinimalOpenApi.ReferencedDocuments.g.cs";

    /// <summary>
    /// Returns the fully qualified (<c>global::</c>) names of the entry points declared by referenced
    /// assemblies, sorted and de-duplicated. The value is equatable so the output is regenerated only
    /// when the set of referenced documents changes.
    /// </summary>
    public static ReferencedEntryPoints Collect(Compilation compilation, CancellationToken cancellationToken)
    {
        var entryPoints = new SortedSet<string>(StringComparer.Ordinal);

        foreach (var reference in compilation.References)
        {
            cancellationToken.ThrowIfCancellationRequested();

            if (compilation.GetAssemblyOrModuleSymbol(reference) is not IAssemblySymbol assembly
                || assembly.Name == RuntimeAssemblyName
                || !ReferencesRuntime(assembly))
                continue;

            foreach (var attribute in assembly.GetAttributes())
            {
                if (attribute.AttributeClass?.ToDisplayString() != DocumentAttributeName
                    || attribute.ConstructorArguments.Length != 1
                    || attribute.ConstructorArguments[0].Value is not INamedTypeSymbol entryPoint
                    || entryPoint.DeclaredAccessibility != Accessibility.Public)
                    continue;

                entryPoints.Add(entryPoint.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
            }
        }

        return new ReferencedEntryPoints(entryPoints.ToArray());
    }

    /// <summary>Generates the module initializer, or <see langword="null"/> when nothing is referenced.</summary>
    public static string? Generate(ReferencedEntryPoints entryPoints, string rootNamespace)
    {
        if (entryPoints.Names.Count == 0)
            return null;

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine($"namespace {rootNamespace};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Registers the MinimalOpenAPI documents declared in referenced assemblies, so that");
        sb.AppendLine("/// <c>AddMinimalOpenApi()</c> and <c>MapMinimalOpenApiEndpoints()</c> include them.");
        sb.AppendLine("/// </summary>");
        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine("internal static class MinimalOpenApiReferencedDocuments");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine("    internal static void Register()");
        sb.AppendLine("    {");
        foreach (var name in entryPoints.Names)
            sb.AppendLine($"        {name}.Register();");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static bool ReferencesRuntime(IAssemblySymbol assembly)
    {
        foreach (var module in assembly.Modules)
        {
            foreach (var referenced in module.ReferencedAssemblies)
            {
                if (referenced.Name == RuntimeAssemblyName)
                    return true;
            }
        }

        return false;
    }
}

/// <summary>Equatable, ordered list of referenced document entry-point names.</summary>
internal sealed class ReferencedEntryPoints(IReadOnlyList<string> names) : IEquatable<ReferencedEntryPoints>
{
    public IReadOnlyList<string> Names { get; } = names;

    public bool Equals(ReferencedEntryPoints? other)
        => other is not null && Names.SequenceEqual(other.Names, StringComparer.Ordinal);

    public override bool Equals(object? obj) => Equals(obj as ReferencedEntryPoints);

    public override int GetHashCode()
    {
        var hash = 17;
        foreach (var name in Names)
            hash = unchecked((hash * 31) + StringComparer.Ordinal.GetHashCode(name));
        return hash;
    }
}