using System.Text;

using MinimalOpenAPI.Abstractions.Models;

namespace MinimalOpenAPI.Generator.CodeGen;

/// <summary>
/// Generates sealed record DTOs and C# enums from OpenAPI component schemas.
/// </summary>
internal static class DtoGenerator
{
    public static DtoGenerationResult Generate(
        Dictionary<string, OpenApiSchema> schemas,
        string rootNamespace,
        string specName,
        SchemaDirectionalityAnalysis directionality,
        SchemaNameMap schemaNameMap,
        SchemaUnionAnalysis unionAnalysis)
    {
        if (schemas.Count == 0 && !unionAnalysis.InlineDefinitions.Any())
            return new DtoGenerationResult(string.Empty, [], [], false);

        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using global::System.Text.Json.Serialization;");
        sb.AppendLine();
        sb.AppendLine($"namespace {rootNamespace}.{specName}.Contracts;");
        sb.AppendLine();

        var emitted = new HashSet<string>(StringComparer.Ordinal);
        var allOfConflicts = new List<AllOfPropertyConflict>();
        var generatedSymbolCollisions = new List<string>();
        var hasUnionTypes = false;

        // Build a set of all normalised top-level component names so that derived names
        // (scoped variants and inline-property types) can be checked for collisions.
        var topLevelNormalisedNames = new HashSet<string>(StringComparer.Ordinal);
        foreach (var key in schemas.Keys)
        {
            var n = schemaNameMap.GetTypeName(key);
            if (!string.IsNullOrEmpty(n))
                topLevelNormalisedNames.Add(n);
        }

        // First pass: emit top-level enum and union schemas.
        foreach (var kvp in schemas)
        {
            if (kvp.Value.Enum is not null)
            {
                var normalizedName = schemaNameMap.GetTypeName(kvp.Key);
                GenerateEnum(sb, normalizedName, kvp.Value, emitted);
            }
            else if (TypeMapper.IsUnionSchema(kvp.Value))
            {
                var normalizedName = schemaNameMap.GetTypeName(kvp.Key);
                if (unionAnalysis.TryGetDefinition(kvp.Value, SchemaGenerationScope.Neutral, out var definition))
                {
                    GenerateUnion(
                        sb,
                        normalizedName,
                        definition,
                        directionality,
                        SchemaGenerationScope.Neutral,
                        emitted,
                        generatedSymbolCollisions,
                        topLevelNormalisedNames);
                    hasUnionTypes = true;
                    EmitInlineCases(definition, SchemaGenerationScope.Neutral);
                }
            }
        }

        // Second pass: emit neutral object schemas as records (with recursive inline-object
        // and inline-enum dependency emission handled inside EmitRecordTree).
        foreach (var kvp in schemas)
        {
            var name = kvp.Key;
            var schema = kvp.Value;
            if (schema.Enum is not null || TypeMapper.IsUnionSchema(schema)) continue;
            var resolvedSchema = AllOfSchemaFlattener.Resolve(schema, schemas, name, allOfConflicts);
            if (resolvedSchema.Type != "object" && resolvedSchema.Reference is null && resolvedSchema.Properties.Count == 0)
                continue;
            if (TypeMapper.IsDictionarySchema(resolvedSchema))
                continue; // pure-dictionary schemas map to Dictionary<string, T> at the use site

            var normalizedName = schemaNameMap.GetTypeName(name);
            EmitRecordTree(sb, normalizedName, resolvedSchema, schemas, emitted, allOfConflicts, directionality, SchemaGenerationScope.Neutral, topLevelNormalisedNames, generatedSymbolCollisions, unionAnalysis);
        }

        // Third pass: emit scoped request/response variants only when required.
        foreach (var kvp in schemas)
        {
            var name = kvp.Key;
            var schema = kvp.Value;
            if (schema.Enum is not null) continue;

            if (TypeMapper.IsUnionSchema(schema))
            {
                var unionName = schemaNameMap.GetTypeName(name);
                if (unionAnalysis.TryGetDefinition(schema, SchemaGenerationScope.Request, out var requestDefinition))
                {
                    GenerateUnion(
                        sb,
                        unionName + "Request",
                        requestDefinition,
                        directionality,
                        SchemaGenerationScope.Request,
                        emitted,
                        generatedSymbolCollisions,
                        topLevelNormalisedNames);
                    hasUnionTypes = true;
                    EmitInlineCases(requestDefinition, SchemaGenerationScope.Request);
                }

                if (unionAnalysis.TryGetDefinition(schema, SchemaGenerationScope.Response, out var responseDefinition))
                {
                    GenerateUnion(
                        sb,
                        unionName + "Response",
                        responseDefinition,
                        directionality,
                        SchemaGenerationScope.Response,
                        emitted,
                        generatedSymbolCollisions,
                        topLevelNormalisedNames);
                    hasUnionTypes = true;
                    EmitInlineCases(responseDefinition, SchemaGenerationScope.Response);
                }

                continue;
            }

            var resolvedSchema = AllOfSchemaFlattener.Resolve(schema, schemas, name, allOfConflicts);
            if (resolvedSchema.Type != "object" && resolvedSchema.Reference is null && resolvedSchema.Properties.Count == 0)
                continue;
            if (TypeMapper.IsDictionarySchema(resolvedSchema))
                continue;

            var normalizedName = schemaNameMap.GetTypeName(name);

            if (directionality.ShouldGenerateScope(name, SchemaGenerationScope.Request))
            {
                var scopedName = normalizedName + "Request";
                if (emitted.Contains(scopedName))
                    generatedSymbolCollisions.Add(scopedName);
                else
                    EmitRecordTree(
                        sb,
                        scopedName,
                        resolvedSchema,
                        schemas,
                        emitted,
                        allOfConflicts,
                        directionality,
                        SchemaGenerationScope.Request,
                        topLevelNormalisedNames,
                        generatedSymbolCollisions,
                        unionAnalysis);
            }

            if (directionality.ShouldGenerateScope(name, SchemaGenerationScope.Response))
            {
                var scopedName = normalizedName + "Response";
                if (emitted.Contains(scopedName))
                    generatedSymbolCollisions.Add(scopedName);
                else
                    EmitRecordTree(
                        sb,
                        scopedName,
                        resolvedSchema,
                        schemas,
                        emitted,
                        allOfConflicts,
                        directionality,
                        SchemaGenerationScope.Response,
                        topLevelNormalisedNames,
                        generatedSymbolCollisions,
                        unionAnalysis);
            }
        }

        foreach (var inline in unionAnalysis.InlineDefinitions)
        {
            if (topLevelNormalisedNames.Contains(inline.Name))
                generatedSymbolCollisions.Add(inline.Name);
            else
            {
                GenerateUnion(sb, inline.Name, inline.Definition, directionality, inline.Scope, emitted, generatedSymbolCollisions, topLevelNormalisedNames);
                EmitInlineCases(inline.Definition, inline.Scope);
                hasUnionTypes = true;
            }
        }

        return new DtoGenerationResult(sb.ToString(), allOfConflicts, generatedSymbolCollisions, hasUnionTypes);

        void EmitInlineCases(SchemaUnionDefinition definition, SchemaGenerationScope scope)
        {
            foreach (var item in definition.Cases)
            {
                if (item.InlineObject is not { } schema)
                    continue;

                if (topLevelNormalisedNames.Contains(item.TypeName) || emitted.Contains(item.TypeName))
                    generatedSymbolCollisions.Add(item.TypeName);
                else
                    EmitRecordTree(sb, item.TypeName, schema, schemas, emitted, allOfConflicts, directionality, scope,
                        topLevelNormalisedNames, generatedSymbolCollisions, unionAnalysis);
            }
        }
    }

    private static void GenerateUnion(
        StringBuilder sb,
        string name,
        SchemaUnionDefinition definition,
        SchemaDirectionalityAnalysis directionality,
        SchemaGenerationScope scope,
        HashSet<string> emitted,
        List<string> generatedSymbolCollisions,
        HashSet<string> topLevelNormalisedNames)
    {
        if (!emitted.Add(name))
        {
            generatedSymbolCollisions.Add(name);
            return;
        }

        var caseTypes = definition.Cases
            .Select(unionCase => unionCase.ComponentReference is { } reference
                ? directionality.ResolveSchemaReference(reference, scope)
                : unionCase.TypeName)
            .ToArray();

        if (definition.ClassifierKind == UnionClassifierKind.Structural)
        {
            sb.AppendLine("[global::System.Text.Json.Serialization.JsonUnion(TypeClassifier = typeof(global::System.Text.Json.Serialization.JsonUnionTypeStructuralClassifier))]");
        }
        else if (definition.ClassifierKind == UnionClassifierKind.Discriminator)
        {
            sb.AppendLine($"[global::System.Text.Json.Serialization.JsonUnion(TypeClassifier = typeof({name}JsonClassifier))]");
        }

        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine($"public union {name}({string.Join(", ", caseTypes)});");
        sb.AppendLine();

        if (definition.ClassifierKind == UnionClassifierKind.Discriminator)
        {
            var classifierName = name + "JsonClassifier";
            if (topLevelNormalisedNames.Contains(classifierName) || !emitted.Add(classifierName))
                generatedSymbolCollisions.Add(classifierName);
            else
                GenerateDiscriminatorClassifier(sb, name, definition, caseTypes);
        }
    }

    private static void GenerateDiscriminatorClassifier(
        StringBuilder sb,
        string unionName,
        SchemaUnionDefinition definition,
        IReadOnlyList<string> caseTypes)
    {
        var propertyNameLiteral = ToCSharpStringLiteral(definition.DiscriminatorPropertyName!);
        var propertyNameBytes = propertyNameLiteral + "u8";

        sb.AppendLine($"public sealed class {unionName}JsonClassifier : global::System.Text.Json.Serialization.JsonTypeClassifierFactory<{unionName}>");
        sb.AppendLine("{");
        sb.AppendLine("    public override global::System.Text.Json.Serialization.JsonTypeClassifier CreateJsonClassifier(");
        sb.AppendLine("        global::System.Text.Json.Serialization.JsonTypeClassifierContext context,");
        sb.AppendLine("        global::System.Text.Json.JsonSerializerOptions options)");
        sb.AppendLine("        => (ref global::System.Text.Json.Utf8JsonReader reader) =>");
        sb.AppendLine("        {");
        sb.AppendLine("            var input = reader;");
        sb.AppendLine("            if (input.TokenType != global::System.Text.Json.JsonTokenType.StartObject)");
        sb.AppendLine($"                throw new global::System.Text.Json.JsonException(\"Expected an object with a '{EscapeStringLiteral(definition.DiscriminatorPropertyName!)}' discriminator.\");");
        sb.AppendLine();
        sb.AppendLine("            global::System.Type? caseType = null;");
        sb.AppendLine("            while (input.Read() && input.TokenType == global::System.Text.Json.JsonTokenType.PropertyName)");
        sb.AppendLine("            {");
        sb.AppendLine($"                var isDiscriminator = input.ValueTextEquals({propertyNameBytes});");
        sb.AppendLine($"                if (!isDiscriminator && options.PropertyNameCaseInsensitive");
        sb.AppendLine($"                    && global::System.String.Equals(input.GetString(), {propertyNameLiteral}, global::System.StringComparison.OrdinalIgnoreCase))");
        sb.AppendLine("                    throw new global::System.Text.Json.JsonException(\"The discriminator property name must use its authored casing.\");");
        sb.AppendLine("                if (!input.Read())");
        sb.AppendLine("                    throw new global::System.Text.Json.JsonException(\"Unexpected end of discriminator object.\");");
        sb.AppendLine();
        sb.AppendLine("                if (!isDiscriminator)");
        sb.AppendLine("                {");
        sb.AppendLine("                    input.Skip();");
        sb.AppendLine("                    continue;");
        sb.AppendLine("                }");
        sb.AppendLine();
        sb.AppendLine("                if (caseType is not null || input.TokenType != global::System.Text.Json.JsonTokenType.String)");
        sb.AppendLine($"                    throw new global::System.Text.Json.JsonException(\"Expected one string '{EscapeStringLiteral(definition.DiscriminatorPropertyName!)}' discriminator.\");");
        sb.AppendLine();
        sb.AppendLine("                caseType = input.GetString() switch");
        sb.AppendLine("                {");
        foreach (var mapping in definition.DiscriminatorMappings)
        {
            sb.AppendLine($"                    {ToCSharpStringLiteral(mapping.Value)} => typeof({caseTypes[mapping.CaseIndex]}),");
        }
        sb.AppendLine($"                    _ => throw new global::System.Text.Json.JsonException(\"Unknown '{EscapeStringLiteral(definition.DiscriminatorPropertyName!)}' discriminator.\")");
        sb.AppendLine("                };");
        sb.AppendLine("            }");
        sb.AppendLine();
        sb.AppendLine($"            return caseType ?? throw new global::System.Text.Json.JsonException(\"Missing '{EscapeStringLiteral(definition.DiscriminatorPropertyName!)}' discriminator.\");");
        sb.AppendLine("        };");
        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static string ToCSharpStringLiteral(string value)
        => $"\"{EscapeStringLiteral(value)}\"";

    private static string EscapeStringLiteral(string value)
    {
        var sb = new StringBuilder(value.Length + 4);
        foreach (var character in value)
        {
            switch (character)
            {
                case '\\': sb.Append("\\\\"); break;
                case '"': sb.Append("\\\""); break;
                case '\n': sb.Append("\\n"); break;
                case '\r': sb.Append("\\r"); break;
                case '\t': sb.Append("\\t"); break;
                default:
                    if (char.IsControl(character))
                        sb.Append($"\\u{(int)character:x4}");
                    else
                        sb.Append(character);
                    break;
            }
        }

        return sb.ToString();
    }

    /// <summary>
    /// Recursively emits the record for <paramref name="schema"/> and all records (and enums)
    /// for its inline properties, ensuring each dependency is emitted before its parent.
    /// The <paramref name="emitted"/> set provides cycle detection and deduplication.
    /// </summary>
    private static void EmitRecordTree(
        StringBuilder sb,
        string name,
        OpenApiSchema schema,
        Dictionary<string, OpenApiSchema> allSchemas,
        HashSet<string> emitted,
        List<AllOfPropertyConflict> allOfConflicts,
        SchemaDirectionalityAnalysis directionality,
        SchemaGenerationScope scope,
        HashSet<string>? topLevelNormalisedNames = null,
        List<string>? generatedSymbolCollisions = null,
        SchemaUnionAnalysis? unions = null)
    {
        if (!emitted.Add(name))
        {
            // If the name is in the top-level set, this is a derived name that collides
            // with an already-emitted component schema — report it.
            if (topLevelNormalisedNames is not null
                && generatedSymbolCollisions is not null
                && topLevelNormalisedNames.Contains(name))
                generatedSymbolCollisions.Add(name);
            return;
        }

        var resolvedSchema = AllOfSchemaFlattener.Resolve(schema, allSchemas, name, allOfConflicts);

        // Emit inline enum property types (dependencies) before the parent record.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (propKvp.Value.Enum is not null)
            {
                var inlineEnumName = name + TypeMapper.ToPascalCase(propKvp.Key);
                var preserveWireValues = unions?.DiscriminatorProperties.Any(discriminator =>
                    discriminator.Property == propKvp.Key
                    && directionality.ResolveSchemaReference(discriminator.Reference, discriminator.Scope) == name) == true;
                GenerateEnum(sb, inlineEnumName, propKvp.Value, emitted, topLevelNormalisedNames, generatedSymbolCollisions, preserveWireValues);
            }
        }

        // Emit inline-object property types (dependencies) before the parent record.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (TypeMapper.IsInlineObject(propKvp.Value))
            {
                var nestedName = name + TypeMapper.ToPascalCase(propKvp.Key);
                EmitRecordTree(sb, nestedName, propKvp.Value, allSchemas, emitted, allOfConflicts, directionality, scope, topLevelNormalisedNames, generatedSymbolCollisions, unions);
            }
        }

        // Emit inline-object value types for dictionary properties (dependencies) before the parent record.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (TypeMapper.IsDictionarySchema(propKvp.Value)
                && propKvp.Value.AdditionalProperties is { } valueSchema
                && TypeMapper.IsInlineObject(valueSchema))
            {
                var valueName = name + TypeMapper.ToPascalCase(propKvp.Key) + "Value";
                EmitRecordTree(sb, valueName, valueSchema, allSchemas, emitted, allOfConflicts, directionality, scope, topLevelNormalisedNames, generatedSymbolCollisions, unions);
            }
        }

        // Emit inline-object and inline-enum item types for array properties (dependencies) before the parent record.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (propKvp.Value.Type?.ToLowerInvariant() == "array" && propKvp.Value.Items is { } itemSchema)
            {
                var itemName = name + TypeMapper.ToPascalCase(propKvp.Key) + "Item";
                EmitArrayItemSchema(sb, itemSchema, itemName, allSchemas, emitted, allOfConflicts, directionality, scope, topLevelNormalisedNames, generatedSymbolCollisions, unions);
            }
        }

        // Build a resolver that maps each inline schema instance to its derived name.
        var inlineMap = new Dictionary<OpenApiSchema, string>();
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (TypeMapper.IsInlineObject(propKvp.Value) || propKvp.Value.Enum is not null)
                inlineMap[propKvp.Value] = name + TypeMapper.ToPascalCase(propKvp.Key);
        }

        // Also map inline-object value types for dictionary properties.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (TypeMapper.IsDictionarySchema(propKvp.Value)
                && propKvp.Value.AdditionalProperties is { } valueSchema
                && TypeMapper.IsInlineObject(valueSchema))
                inlineMap[valueSchema] = name + TypeMapper.ToPascalCase(propKvp.Key) + "Value";
        }

        // Also map inline-object and inline-enum item types for array properties.
        foreach (var propKvp in resolvedSchema.Properties)
        {
            if (!directionality.ShouldIncludeProperty(propKvp.Value, scope))
                continue;

            if (propKvp.Value.Type?.ToLowerInvariant() == "array" && propKvp.Value.Items is { } itemSchema)
            {
                var itemName = name + TypeMapper.ToPascalCase(propKvp.Key) + "Item";
                BuildArrayItemInlineMap(itemSchema, itemName, inlineMap);
            }
        }

        InlineSchemaResolver resolveInline =
            s => unions?.ResolveInline(s, scope) ?? (inlineMap.TryGetValue(s, out var n) ? n : null);

        GenerateRecord(sb, name, resolvedSchema, directionality, scope, resolveInline);
        sb.AppendLine();
    }

    /// <summary>
    /// Emits the record or enum for an array item schema, recursing into inner items when
    /// the item schema is itself an array (array-of-array support).
    /// </summary>
    private static void EmitArrayItemSchema(
        StringBuilder sb,
        OpenApiSchema itemSchema,
        string itemName,
        Dictionary<string, OpenApiSchema> allSchemas,
        HashSet<string> emitted,
        List<AllOfPropertyConflict> allOfConflicts,
        SchemaDirectionalityAnalysis directionality,
        SchemaGenerationScope scope,
        HashSet<string>? topLevelNormalisedNames = null,
        List<string>? generatedSymbolCollisions = null,
        SchemaUnionAnalysis? unions = null)
    {
        if (TypeMapper.IsInlineObject(itemSchema))
        {
            EmitRecordTree(sb, itemName, itemSchema, allSchemas, emitted, allOfConflicts, directionality, scope, topLevelNormalisedNames, generatedSymbolCollisions, unions);
        }
        else if (itemSchema.Enum is not null)
        {
            GenerateEnum(sb, itemName, itemSchema, emitted, topLevelNormalisedNames, generatedSymbolCollisions);
        }
        else if (itemSchema.Type?.ToLowerInvariant() == "array" && itemSchema.Items is { } innerItemSchema)
        {
            // array-of-array: walk into the inner item schema using an extra "Item" suffix.
            EmitArrayItemSchema(sb, innerItemSchema, itemName + "Item", allSchemas, emitted, allOfConflicts, directionality, scope, topLevelNormalisedNames, generatedSymbolCollisions, unions);
        }
    }

    /// <summary>
    /// Populates <paramref name="inlineMap"/> with inline schema → type-name entries for
    /// array item schemas, recursing through nested arrays (array-of-array support).
    /// </summary>
    private static void BuildArrayItemInlineMap(
        OpenApiSchema itemSchema,
        string itemName,
        Dictionary<OpenApiSchema, string> inlineMap)
    {
        if (TypeMapper.IsInlineObject(itemSchema) || itemSchema.Enum is not null)
        {
            inlineMap[itemSchema] = itemName;
        }
        else if (itemSchema.Type?.ToLowerInvariant() == "array" && itemSchema.Items is { } innerItemSchema)
        {
            BuildArrayItemInlineMap(innerItemSchema, itemName + "Item", inlineMap);
        }
    }

    private static void GenerateEnum(
        StringBuilder sb,
        string name,
        OpenApiSchema schema,
        HashSet<string> emitted,
        HashSet<string>? topLevelNormalisedNames = null,
        List<string>? generatedSymbolCollisions = null,
        bool preserveWireValues = false)
    {
        if (!emitted.Add(name))
        {
            // If this inline enum name collides with an already-emitted top-level component,
            // report it as a generated-symbol collision rather than silently skipping.
            if (topLevelNormalisedNames is not null
                && generatedSymbolCollisions is not null
                && topLevelNormalisedNames.Contains(name))
                generatedSymbolCollisions.Add(name);
            return;
        }

        sb.AppendLine($"/// <summary>Generated enum for schema <c>{name}</c>.</summary>");
        sb.AppendLine($"[global::System.CodeDom.Compiler.GeneratedCode(\"{TypeMapper.GeneratorName}\", \"{TypeMapper.GeneratorVersion}\")]");
        sb.AppendLine("[JsonConverter(typeof(JsonStringEnumConverter))]");
        sb.AppendLine($"public enum {name}");
        sb.AppendLine("{");

        var values = schema.Enum!;
        for (var i = 0; i < values.Count; i++)
        {
            var member = TypeMapper.ToEnumMemberName(values[i]);
            if (preserveWireValues)
                sb.AppendLine($"    [JsonStringEnumMemberName({ToCSharpStringLiteral(values[i])})]");
            sb.Append($"    {member}");
            sb.AppendLine(i < values.Count - 1 ? "," : string.Empty);
        }

        sb.AppendLine("}");
        sb.AppendLine();
    }

    private static void GenerateRecord(
        StringBuilder sb,
        string name,
        OpenApiSchema schema,
        SchemaDirectionalityAnalysis directionality,
        SchemaGenerationScope scope,
        InlineSchemaResolver? resolveInline = null)
    {
        sb.AppendLine($"/// <summary>Generated DTO for schema <c>{name}</c>.</summary>");
        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine($"public sealed record {name}");
        sb.AppendLine("{");
        var hadDeclaredProperties = schema.Properties.Count > 0;

        foreach (var propKvp in schema.Properties)
        {
            var propName = propKvp.Key;
            var propSchema = propKvp.Value;
            if (!directionality.ShouldIncludeProperty(propSchema, scope))
                continue;
            var isRequired = schema.Required.Contains(propName, StringComparer.OrdinalIgnoreCase);
            var nullable = propSchema.Nullable || !isRequired;
            var typeName = TypeMapper.MapSchema(
                propSchema,
                nullable: nullable,
                resolveInline: resolveInline,
                resolveReference: referenceName => directionality.ResolveSchemaReference(referenceName, scope));
            var csharpName = TypeMapper.ToPascalCase(propName);

            sb.AppendLine($"    [JsonPropertyName(\"{propName}\")]");

            foreach (var attr in ValidationAttributeEmitter.GetAttributes(propSchema, "    "))
                sb.AppendLine(attr);

            if (nullable)
            {
                sb.AppendLine($"    public {typeName} {csharpName} {{ get; init; }}");
            }
            else
            {
                sb.AppendLine($"    public required {typeName} {csharpName} {{ get; init; }}");
            }
        }

        // When additionalProperties: true is set alongside named properties, capture
        // any extra key-value pairs via [JsonExtensionData].
        if (schema.AdditionalPropertiesAllowed && hadDeclaredProperties)
        {
            sb.AppendLine($"    [JsonExtensionData]");
            sb.AppendLine($"    public global::System.Collections.Generic.Dictionary<string, global::System.Text.Json.JsonElement>? Extensions {{ get; init; }}");
        }

        sb.AppendLine("}");
    }
}

internal sealed record DtoGenerationResult(
    string Source,
    IReadOnlyList<AllOfPropertyConflict> AllOfConflicts,
    IReadOnlyList<string> GeneratedSymbolCollisions,
    bool HasUnionTypes);