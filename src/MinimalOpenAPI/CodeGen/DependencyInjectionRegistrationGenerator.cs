using System.Text;

using MinimalOpenAPI.Abstractions.Models;

namespace MinimalOpenAPI.Generator.CodeGen;

/// <summary>
/// Generates the DI registration extension method for all discovered handlers.
/// </summary>
internal static class DependencyInjectionRegistrationGenerator
{
    public static string Generate(
        List<OpenApiOperation> operations,
        List<DiscoveredImplementation> handlers,
        List<DiscoveredImplementation> configurations,
        string rootNamespace,
        string specName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.AppendLine("using global::Microsoft.Extensions.DependencyInjection;");
        sb.AppendLine();
        sb.AppendLine($"namespace {rootNamespace}.{specName}.Endpoints;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>Generated DI registration for MinimalOpenAPI handlers.</summary>");
        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine("public static class MinimalOpenApiGeneratedServiceCollectionExtensions");
        sb.AppendLine("{");
        sb.AppendLine("    /// <summary>Registers all generated endpoint handlers and endpoint configurations.</summary>");
        sb.AppendLine("    public static global::Microsoft.Extensions.DependencyInjection.IServiceCollection AddGeneratedEndpoints(");
        sb.AppendLine("        this global::Microsoft.Extensions.DependencyInjection.IServiceCollection services)");
        sb.AppendLine("    {");

        foreach (var op in operations)
        {
            var handlerBase = TypeMapper.HandlerClassName(op.OperationId);
            var handlerImpl = handlers.FirstOrDefault(h => h.BaseName == handlerBase);
            if (handlerImpl is not null)
            {
                // Register concrete implementation
                sb.AppendLine($"        services.AddScoped<global::{rootNamespace}.{specName}.Endpoints.{handlerBase}, global::{handlerImpl.FullName}>();");
            }
            else
            {
                // No implementation found — register the base class so the endpoint resolves at runtime
                // (it will throw NotImplementedException when invoked, matching MOA001). TryAdd, so an
                // implementation registered by a referencing project always takes precedence.
                sb.AppendLine($"        global::Microsoft.Extensions.DependencyInjection.Extensions.ServiceCollectionDescriptorExtensions.TryAddScoped<global::{rootNamespace}.{specName}.Endpoints.{handlerBase}>(services);");
            }

            var configurationBase = TypeMapper.EndpointConfigurationBaseClassName(op.OperationId);
            var configurationImpl = configurations.FirstOrDefault(c => c.BaseName == configurationBase);
            if (configurationImpl is not null)
            {
                sb.AppendLine($"        services.AddSingleton<global::{rootNamespace}.{specName}.Endpoints.{configurationBase}, global::{configurationImpl.FullName}>();");
            }
        }

        sb.AppendLine("        return services;");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Registers this document through <see cref=\"global::{rootNamespace}.{specName}.{EntryPointClassName(specName)}.Register\"/>");
        sb.AppendLine("/// when this assembly is loaded. Projects referencing this assembly register it too, from their own");
        sb.AppendLine("/// generated module initializer, so registration never depends on this assembly being loaded first.");
        sb.AppendLine("/// </summary>");
        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine("internal static class MinimalOpenApiModuleInitializer");
        sb.AppendLine("{");
        sb.AppendLine("    [global::System.Runtime.CompilerServices.ModuleInitializer]");
        sb.AppendLine($"    internal static void Register() => global::{rootNamespace}.{specName}.{EntryPointClassName(specName)}.Register();");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static void AppendTypes(StringBuilder sb, string property, IReadOnlyList<string>? types, string rootNamespace, string specName)
    {
        if (types is not { Count: > 0 })
            return;
        sb.Append($", {property} = new global::System.Type[] {{ ");
        sb.Append(string.Join(", ", types.Select(t => $"typeof(global::{rootNamespace}.{specName}.Endpoints.{t})")));
        sb.Append(" }");
    }

    /// <summary>
    /// Generates the assembly attribute that lets projects generating only <c>Endpoints</c> for the
    /// same document find these contract types.
    /// </summary>
    public static string GenerateContractsMarker(string specName, string contractsNamespace, string documentHash)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine();
        sb.AppendLine(
            $"[assembly: global::MinimalOpenAPI.MinimalOpenApiContracts(\"{EscapeCSharpStringLiteral(specName)}\", " +
            $"\"{EscapeCSharpStringLiteral(contractsNamespace)}\", \"{documentHash}\")]");
        return sb.ToString();
    }

    /// <summary>Name of the public entry-point class generated for an OpenAPI document.</summary>
    public static string EntryPointClassName(string specName) => specName + "MinimalOpenApi";

    /// <summary>
    /// Generates the public entry point of an OpenAPI document: a static class whose idempotent
    /// <c>Register()</c> wires the document's DI registration, endpoint mapping and schema file into
    /// the MinimalOpenAPI runtime, plus the assembly-level <c>MinimalOpenApiDocument</c> marker that
    /// lets referencing projects discover and call it at build time.
    /// </summary>
    public static string GenerateEntryPoint(
        string rootNamespace,
        string specName,
        string schemaId,
        string specFileName,
        string? publishAs,
        string? displayName,
        string? displayVersion,
        IReadOnlyList<string>? unimplementedHandlers = null,
        IReadOnlyList<string>? implementedConfigurations = null)
    {
        var className = EntryPointClassName(specName);
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();
        sb.Append($"[assembly: global::MinimalOpenAPI.MinimalOpenApiDocument(typeof(global::{rootNamespace}.{specName}.{className})");
        AppendTypes(sb, "UnimplementedHandlers", unimplementedHandlers, rootNamespace, specName);
        AppendTypes(sb, "ImplementedConfigurations", implementedConfigurations, rootNamespace, specName);
        sb.AppendLine(")]");
        sb.AppendLine();
        sb.AppendLine($"namespace {rootNamespace}.{specName};");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine($"/// Generated entry point of the <c>{specName}</c> OpenAPI document.");
        sb.AppendLine("/// </summary>");
        TypeMapper.AppendGeneratedAttributes(sb);
        sb.AppendLine($"public static class {className}");
        sb.AppendLine("{");
        sb.AppendLine("    private static int _registered;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Registers this document's handlers, endpoint configurations, endpoint mapping and schema file");
        sb.AppendLine("    /// with <c>AddMinimalOpenApi()</c>, <c>MapMinimalOpenApiEndpoints()</c> and <c>MapOpenApiSchemas()</c>.");
        sb.AppendLine("    /// Calling it more than once has no further effect.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    /// <remarks>");
        sb.AppendLine("    /// The generated module initializers of this assembly and of every project that references it call");
        sb.AppendLine("    /// this method automatically. Call it yourself, before <c>AddMinimalOpenApi()</c>, only from a host");
        sb.AppendLine("    /// in which the MinimalOpenAPI source generator does not run.");
        sb.AppendLine("    /// </remarks>");
        sb.AppendLine("    public static void Register()");
        sb.AppendLine("    {");
        sb.AppendLine("        if (global::System.Threading.Interlocked.Exchange(ref _registered, 1) != 0)");
        sb.AppendLine("            return;");
        sb.AppendLine();
        sb.AppendLine("        global::MinimalOpenAPI.ServiceCollectionExtensions.RegisterGeneratedServices(");
        sb.AppendLine($"            static services => global::{rootNamespace}.{specName}.Endpoints.MinimalOpenApiGeneratedServiceCollectionExtensions.AddGeneratedEndpoints(services));");
        sb.AppendLine("        global::MinimalOpenAPI.ServiceCollectionExtensions.RegisterEndpointMapping(");
        sb.AppendLine($"            static (builder, group) => global::{rootNamespace}.{specName}.Endpoints.MinimalOpenApiGeneratedEndpointRouteBuilderExtensions.MapEndpoints(builder, group));");
        if (!string.IsNullOrEmpty(schemaId))
        {
            var relPath = $"openapi/schemas/{schemaId}/{specFileName}";
            var escapedRelPath = EscapeCSharpStringLiteral(relPath);
            var escapedPublishAs = EscapeCSharpStringLiteral(publishAs);
            var escapedDisplayName = EscapeCSharpStringLiteral(displayName);
            var escapedDisplayVersion = EscapeCSharpStringLiteral(displayVersion);
            sb.AppendLine(
                $"        global::MinimalOpenAPI.ServiceCollectionExtensions.RegisterSchemaFile(\"{escapedRelPath}\", " +
                $"{AsNullableCSharpStringLiteral(escapedPublishAs)}, " +
                $"{AsNullableCSharpStringLiteral(escapedDisplayName)}, " +
                $"{AsNullableCSharpStringLiteral(escapedDisplayVersion)});");
        }
        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string? EscapeCSharpStringLiteral(string? value) =>
        value is null ? null : value.Replace("\\", "\\\\").Replace("\"", "\\\"");

    private static string AsNullableCSharpStringLiteral(string? value) =>
        value is null ? "null" : $"\"{value}\"";
}

/// <summary>Represents a discovered concrete implementation of a generated base class.</summary>
internal sealed class DiscoveredImplementation
{
    public string BaseName { get; init; } = string.Empty;
    public string FullName { get; init; } = string.Empty;
}